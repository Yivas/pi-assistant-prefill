import { createHash, randomBytes, randomUUID } from "node:crypto";
import type { Stats } from "node:fs";
import fs from "node:fs/promises";
import path from "node:path";
import {
  CONFIGURATION_SCHEMA_VERSION,
  type ConfigurationDocument,
  isBindingId,
  isRegistryIdentifier,
  type ProfileBinding,
  type ProfileConfiguration,
  parseProfileConfiguration,
  readConfigurationDocument,
  sameBindingRule,
} from "./config.ts";
import { ProfileFailure } from "./diagnostic.ts";
import { fileOperation, lstatIfPresent, readRegularFileWithin } from "./file-read.ts";
import { CONFIGURATION_FILE_NAME, isProfileId } from "./profiles.ts";
import { MAX_JSON_DOCUMENT_BYTES } from "./strict-json.ts";

// Only the TUI menu calls this writer. Everything is validated before the first byte is written, and
// every failure this module can name is returned instead of thrown; a defect in its own logic still
// propagates.
export type ConfigWriteFailure =
  | "invalid-binding"
  | "duplicate-binding"
  | "invalid-configuration"
  | "size"
  | "config-changed"
  | "unsafe-path"
  | "io";

export type ConfigWriteResult =
  | { readonly status: "saved" }
  | {
      readonly status: "failed";
      readonly reason: ConfigWriteFailure;
      readonly detail: string | null;
    };

// A rule the operator asked for. The identifier is generated by this module, never by a caller.
export interface ProfileBindingRequest {
  readonly profileId: string;
  readonly provider: string;
  readonly model: string | null;
}

class WriteError extends Error {
  readonly reason: ConfigWriteFailure;

  constructor(reason: ConfigWriteFailure) {
    super(reason);
    this.reason = reason;
  }
}

export async function addProfileBinding(
  libraryRoot: string,
  request: ProfileBindingRequest,
): Promise<ConfigWriteResult> {
  return updateConfiguration(libraryRoot, (configuration) => {
    if (!isBindingRequest(request)) throw new WriteError("invalid-binding");
    // The identifier is generated after the spread, so a caller cannot replace it.
    const binding: ProfileBinding = { ...request, id: newBindingId() };
    if (configuration.bindings.some((existing) => sameBindingRule(existing, binding))) {
      throw new WriteError("duplicate-binding");
    }
    return { ...configuration, bindings: [...configuration.bindings, binding] };
  });
}

// Removes every rule that carries the identifier. The reader allows two rules to share one
// identifier, so the removal is stated rather than assumed to find exactly one.
export async function removeProfileBinding(
  libraryRoot: string,
  bindingId: string,
): Promise<ConfigWriteResult> {
  if (!isBindingId(bindingId)) return failed("invalid-binding", null);
  return updateConfiguration(libraryRoot, (configuration) => ({
    ...configuration,
    bindings: configuration.bindings.filter((binding) => binding.id !== bindingId),
  }));
}

// Read, change and replace. The document that was read is the only one this write may replace: its
// digest is checked again just before the rename, and a different file is reported, not overwritten.
// A version 1 file is migrated on the way out, because the writer always saves the current version.
async function updateConfiguration(
  libraryRoot: string,
  update: (configuration: ProfileConfiguration) => ProfileConfiguration,
): Promise<ConfigWriteResult> {
  try {
    const document = await readConfigurationForWrite(libraryRoot);
    const configuration =
      document.bytes === null
        ? { defaultProfileId: null, bindings: [] }
        : parseProfileConfiguration(document.bytes);
    const text = serializeConfiguration(update(configuration));
    if (Buffer.byteLength(text) > MAX_JSON_DOCUMENT_BYTES) throw new WriteError("size");
    requireReadableConfiguration(text);
    await replaceConfiguration(document, digestOf(document.bytes), text);
    return { status: "saved" };
  } catch (error) {
    if (error instanceof WriteError) return failed(error.reason, null);
    if (error instanceof ProfileFailure) {
      return failed(configurationFailure(error), `${error.category}/${error.code}`);
    }
    // Only a file system error is reported as io. Anything else is a defect, not a write failure.
    if (hasSystemErrorCode(error)) return failed("io", null);
    throw error;
  }
}

// The writer must never save a document that the reader rejects, so the serialized text goes back
// through the reader's parser before it reaches the file.
function requireReadableConfiguration(text: string): void {
  try {
    parseProfileConfiguration(Buffer.from(text, "utf8"));
  } catch (error) {
    if (error instanceof ProfileFailure) throw new WriteError("invalid-configuration");
    throw error;
  }
}

function hasSystemErrorCode(error: unknown): boolean {
  if (typeof error !== "object" || error === null || !("code" in error)) return false;
  return typeof error.code === "string";
}

async function readConfigurationForWrite(libraryRoot: string): Promise<ConfigurationDocument> {
  await fileOperation(() => fs.mkdir(libraryRoot, { recursive: true }));
  const document = await readConfigurationDocument(libraryRoot);
  // The directory was just created, so an absent root is not a library the writer can use.
  if (document === null) throw new WriteError("io");
  return document;
}

function serializeConfiguration(configuration: ProfileConfiguration): string {
  const document = {
    schemaVersion: CONFIGURATION_SCHEMA_VERSION,
    defaultProfileId: configuration.defaultProfileId,
    bindings: configuration.bindings.map((binding) => ({
      id: binding.id,
      profileId: binding.profileId,
      provider: binding.provider,
      model: binding.model,
    })),
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

// The new content goes to a temporary file in the same directory and replaces the configuration with
// a rename. The previous file is never removed first, so an interrupted write keeps one of the two.
async function replaceConfiguration(
  document: ConfigurationDocument,
  expectedDigest: string | null,
  text: string,
): Promise<void> {
  checkTarget(await lstatIfPresent(document.path));
  const temporaryPath = path.join(
    document.realRoot,
    `.${CONFIGURATION_FILE_NAME}.${randomUUID()}.tmp`,
  );
  let temporaryExists = false;
  try {
    const handle = await fileOperation(() => fs.open(temporaryPath, "wx", 0o600));
    temporaryExists = true;
    try {
      await fileOperation(() => handle.writeFile(text));
      await fileOperation(() => handle.sync());
    } finally {
      await fileOperation(() => handle.close());
    }
    checkTarget(await lstatIfPresent(document.path));
    if ((await currentDigest(document)) !== expectedDigest) {
      throw new WriteError("config-changed");
    }
    await fileOperation(() => fs.rename(temporaryPath, document.path));
    temporaryExists = false;
  } finally {
    if (temporaryExists) await fs.rm(temporaryPath, { force: true }).catch(() => undefined);
  }
}

// Re-reads the file the write is about to replace. A file that cannot be read again, or that is no
// longer the regular file that was validated, counts as a change of the file.
async function currentDigest(document: ConfigurationDocument): Promise<string | null> {
  if ((await lstatIfPresent(document.path)) === null) return null;
  try {
    const bytes = await readRegularFileWithin(
      document.realRoot,
      document.path,
      MAX_JSON_DOCUMENT_BYTES,
    );
    return digestOf(bytes);
  } catch (error) {
    if (error instanceof ProfileFailure) throw new WriteError("config-changed");
    throw error;
  }
}

function checkTarget(stats: Stats | null): void {
  if (stats !== null && (!stats.isFile() || stats.isSymbolicLink())) {
    throw new WriteError("unsafe-path");
  }
}

function digestOf(bytes: Buffer | null): string | null {
  return bytes === null ? null : createHash("sha256").update(bytes).digest("hex");
}

// The three predicates accept unknown values, so a request that arrives without the expected types
// is reported instead of throwing inside a path or identifier helper.
function isBindingRequest(request: ProfileBindingRequest): boolean {
  return (
    isProfileId(request.profileId) &&
    isRegistryIdentifier(request.provider) &&
    (request.model === null || isRegistryIdentifier(request.model))
  );
}

function newBindingId(): string {
  return `b-${randomBytes(4).toString("hex")}`;
}

function configurationFailure(error: ProfileFailure): ConfigWriteFailure {
  return error.category === "configuration" || error.category === "size"
    ? "invalid-configuration"
    : "io";
}

function failed(reason: ConfigWriteFailure, detail: string | null): ConfigWriteResult {
  return { status: "failed", reason, detail };
}
